package org.apache.camel.quarkus.core.tls.it;

import java.io.InputStream;
import java.nio.file.Files;
import java.nio.file.Path;
import java.security.KeyStore;
import java.security.cert.X509Certificate;
import java.time.Duration;
import java.util.Collections;

import io.restassured.RestAssured;
import io.smallrye.certs.CertificateGenerator;
import io.smallrye.certs.CertificateRequest;
import io.smallrye.certs.Format;

import static java.nio.file.StandardCopyOption.ATOMIC_MOVE;
import static java.nio.file.StandardCopyOption.REPLACE_EXISTING;

/**
 * Rotates PKCS12 key stores generated by {@code @TestCertificates}, and reads the state of the routes in
 * {@link TlsRegistryReloadRoutes}.
 */
final class CertificateRotation {
    static final String CERTS_DIR = "target/certs";
    static final String PASSWORD = "changeit";

    private CertificateRotation() {
    }

    /**
     * Regenerate the key store of a certificate. It is written to a temporary directory and moved into place in one
     * step, so that the reload never reads a partly written file.
     *
     * @return the serial number of the new certificate, in hex
     */
    static String rotate(String name) throws Exception {
        regenerate(name, false, keyStoreFileName(name));
        return serial(name);
    }

    /**
     * Regenerate a certificate generated with {@code client = true}, and replace only the trust store that the server
     * uses to verify clients. The current client certificate is then no longer trusted.
     */
    static void rotateServerTrustStore(String name) throws Exception {
        regenerate(name, true, name + "-server-truststore.p12");
    }

    private static void regenerate(String name, boolean client, String fileName) throws Exception {
        Path target = Path.of(CERTS_DIR, fileName);
        Path dir = Files.createTempDirectory(target.getParent(), "rotation");
        try {
            new CertificateGenerator(dir, true).generate(new CertificateRequest()
                    .withName(name)
                    .withClientCertificate(client)
                    .withFormat(Format.PKCS12)
                    .withPassword(PASSWORD)
                    .withDuration(Duration.ofDays(1)));
            Files.move(dir.resolve(fileName), target, ATOMIC_MOVE, REPLACE_EXISTING);
        } finally {
            try (var files = Files.list(dir)) {
                for (Path file : files.toList()) {
                    Files.delete(file);
                }
            }
            Files.delete(dir);
        }
    }

    /**
     * The serial number of the certificate in the key store, in hex.
     */
    static String serial(String name) throws Exception {
        KeyStore keyStore = KeyStore.getInstance("PKCS12");
        try (InputStream in = Files.newInputStream(Path.of(CERTS_DIR, keyStoreFileName(name)))) {
            keyStore.load(in, PASSWORD.toCharArray());
        }
        for (String alias : Collections.list(keyStore.aliases())) {
            if (keyStore.isKeyEntry(alias)) {
                return ((X509Certificate) keyStore.getCertificate(alias)).getSerialNumber().toString(16);
            }
        }
        throw new IllegalStateException("No key entry in " + name);
    }

    static String keyStorePath(String name) {
        return CERTS_DIR + "/" + keyStoreFileName(name);
    }

    private static String keyStoreFileName(String name) {
        return name + "-keystore.p12";
    }

    /**
     * Sends a message to a route, returning the reply, or the error message with status 500.
     */
    static String call(String routeId) {
        return RestAssured.get("/tls-registry/reload/route/" + routeId + "/call").asString();
    }

    static int starts(String routeId) {
        return Integer.parseInt(startsAndTime(routeId)[0]);
    }

    static long lastStarted(String routeId) {
        return Long.parseLong(startsAndTime(routeId)[1]);
    }

    private static String[] startsAndTime(String routeId) {
        return RestAssured.get("/tls-registry/reload/route/" + routeId + "/starts").asString().split(",");
    }

    static int certificateUpdates(String tlsConfiguration) {
        return Integer.parseInt(RestAssured.get("/tls-registry/reload/certificate-updates/" + tlsConfiguration).asString());
    }

    static String status(String routeId) {
        return RestAssured.get("/tls-registry/reload/route/" + routeId + "/status").asString();
    }
}
